import YAML from 'yaml';
import fs from 'node:fs';
import { CiConfigError } from './pipelineConfig.js';

/**
 * The CI of an SPL: what a merge request on the line does to the products that exist. Its settings are kept in the repository of the line
 * (`.linea/ci.json`) and rendered onto the template that ships with LINEA (`spl-gitlab-ci.yml`): the template says what the checks are, the
 * settings say how many products they take, which of them run and on which runners. Pure.
 */
export const SPL_CI_CONFIG_PATH = '.linea/ci.json';
export const SPL_CI_FILE_PATH = '.gitlab-ci.yml';

const TEMPLATE_URL = new URL('./../templates/pipeline/spl-gitlab-ci.yml', import.meta.url);
let template = null;
export const splTemplate = () => (template ??= fs.readFileSync(TEMPLATE_URL, 'utf8'));

export const defaultSplCi = () => ({
  enabled: false,
  tags: ['deploy'],
  // where the jobs install linea-ci from: an npm name, a git URL or a tarball (what `npm install --global` takes)
  package: 'git+https://$CI_SERVER_HOST/linea/linea-ci.git',
  // how many products a merge request regenerates (the ones sharing the features it touches go first)
  maxProducts: 5,
  // how many configurations of the pairwise sample a scheduled pipeline derives
  maxSamples: 30,
  // the cyclomatic complexity above which a function of the generated code is flagged
  maxCcn: 15,
  metrics: true,
  pairwise: true,
  version: true,
  release: true,
  security: true,
});

const whole = (value, fallback, label, min, max) => {
  const number = Number(value ?? fallback);
  if (!Number.isInteger(number) || number < min || number > max) throw new CiConfigError(`${label} must be a whole number from ${min} to ${max}`);
  return number;
};

export const normalizeSplCi = (raw) => {
  const base = defaultSplCi();
  if (raw == null) return base;
  if (typeof raw !== 'object' || Array.isArray(raw)) throw new CiConfigError('the CI configuration must be an object');
  const tags = (Array.isArray(raw.tags) ? raw.tags : base.tags).map((tag) => String(tag).trim()).filter(Boolean);
  if (tags.some((tag) => tag.length > 60)) throw new CiConfigError('a runner tag is at most 60 characters');
  const flag = (key) => (raw[key] === undefined ? base[key] : raw[key] === true);
  const pkg = String(raw.package ?? base.package).trim();
  if (!pkg || pkg.length > 300 || /[\s"'`;&|<>\\()]/.test(pkg)) throw new CiConfigError('the package of linea-ci must be an npm name, a git URL or a tarball (it may use $VARIABLES), without spaces, quotes or shell characters');
  return {
    enabled: raw.enabled === true,
    tags,
    package: pkg,
    maxProducts: whole(raw.maxProducts, base.maxProducts, 'the number of products', 1, 200),
    maxSamples: whole(raw.maxSamples, base.maxSamples, 'the number of samples', 1, 500),
    maxCcn: whole(raw.maxCcn, base.maxCcn, 'the complexity limit', 1, 200),
    metrics: flag('metrics'),
    pairwise: flag('pairwise'),
    version: flag('version'),
    release: flag('release'),
    security: flag('security'),
  };
};

export const serializeSplCi = (config) => `${JSON.stringify(config, null, 2)}\n`;

export const parseSplCi = (content) => {
  if (content == null || !String(content).trim()) return defaultSplCi();
  try {
    return normalizeSplCi(JSON.parse(content));
  } catch (error) {
    console.error(`[ci] ${SPL_CI_CONFIG_PATH} of a line is not valid, CI is treated as off: ${error.message}`);
    return defaultSplCi();
  }
};

const HEADER = [
  'CI of the SPL. It is generated by LINEA from .linea/ci.json: edit it in the CI/CD tab of the line, not here.',
  'What the checks are is in the documentation of linea-ci; here only how many products they take and which of them run.',
].map((line) => `# ${line}`).join('\n');

// the jobs each switch takes out when it is off
const SWITCHES = { metrics: ['metrics'], pairwise: ['sample', 'samples'], version: ['version'], release: ['release'] };

/** The `.gitlab-ci.yml` of a configuration, or `null` when CI is off. */
export const renderSplPipeline = (config, source = splTemplate()) => {
  if (!config?.enabled) return null;
  const doc = YAML.parse(source);
  doc.variables = {
    ...doc.variables,
    LINEA_CI_PACKAGE: config.package,
    LINEA_CI_MAX_PRODUCTS: String(config.maxProducts),
    LINEA_CI_MAX_SAMPLES: String(config.maxSamples),
    LINEA_CI_MAX_CCN: String(config.maxCcn),
    // the jobs of the child pipelines linea-ci writes ask for these tags too
    ...(config.tags.length ? { LINEA_CI_TAGS: config.tags.join(',') } : {}),
  };
  if (config.tags.length) doc['.linea-ci'].tags = config.tags;
  for (const [key, jobs] of Object.entries(SWITCHES)) {
    if (config[key]) continue;
    for (const job of jobs) delete doc[job];
  }
  if (!config.security) delete doc.include;
  // a job cannot wait for one that is gone
  for (const job of Object.values(doc)) {
    if (Array.isArray(job?.needs)) job.needs = job.needs.filter((name) => name in doc);
  }
  return `${HEADER}\n\n${YAML.stringify(doc, { lineWidth: 0, aliasDuplicateObjects: false })}`;
};
